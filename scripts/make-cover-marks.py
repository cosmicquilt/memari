# THE MARKS ON A PRINTED COVER (2026-11-01): "m." and "memari." as the
# carousel drew them, in each finish a cover uses, written into
# src/lib/print/coverMarks.generated.ts for the cover's PDF.
#
#   handoff/ml/.venv/Scripts/python.exe scripts/make-cover-marks.py <Inter variable woff2 or ttf>
#
# (Inter is not bundled for print; next/font keeps a copy of it in
# .next/static/media after any dev run - the one whose name starts
# 83afe278, as the carousel's scripts used.)
#
# Each mark is drawn at 1200 pixels to the inch at its largest printed size
# - a picture fine enough that its edges print as sharp as type - cropped to
# its ink, and coloured for its finish:
#
#   imprint  the cover's own grain darkened inside the letters (black at 30%,
#            so the grain shows through: "a printed shadow"), with the walls
#            of a pressed letter lit from the upper left - a darker rim on
#            the inner upper-left edges, a lighter one on the lower-right
#   gold     gold-coloured ink, the same rims a touch darker and lighter
#
# The faces are the carousel's (memari-checkout-mockups): the m. in Inter
# 700 with the full stop drawn 0.03em in, the wordmark in Newsreader 600 or
# Inter 700 tracked -0.03em.

import base64, io, sys
import numpy as np
from PIL import Image, ImageDraw, ImageFont

INTER = sys.argv[1]
NEWSREADER = "assets/fonts/Newsreader.ttf"
OUT = "src/lib/print/coverMarks.generated.ts"
PPI = 1200

# the widest each is printed (catalogue measurements on a 7in front), inches
SHAPES = {
    "m-sans": ("m.", "sans", 0.132 * 7),
    "memari-sans": ("memari.", "sans", 0.257 * 7),
    "memari-serif": ("memari.", "serif", 0.257 * 7),
}
# every shape in every finish: any cover takes any mark in imprint or gold
# (2026-11-05), and a gold mark is printed in the cover's own gold - bright,
# deep on a light cover, dark on kraft (catalogue.ts goldTone). Until then
# each shape had only the finishes its pictures used (coverCarousel.json).
FINISHES = {shape: ["imprint", "gold", "deep", "dark"] for shape in ("m-sans", "memari-sans", "memari-serif")}
GOLD = {"gold": (194, 160, 96), "deep": (158, 122, 60), "dark": (94, 69, 32)}


def coverage(text, face, width_in):
    big = 1600
    if face == "sans":
        font = ImageFont.truetype(INTER, big)
        font.set_variation_by_axes([700])
        track = -0.03 * big
    else:
        font = ImageFont.truetype(NEWSREADER, big)
        font.set_variation_by_axes([600, 18])
        track = 0.0
    canvas = Image.new("L", (int(big * (len(text) + 1)), big * 2), 0)
    draw = ImageDraw.Draw(canvas)
    x = big * 0.2
    for ch in text:
        draw.text((x, big * 0.2), ch, font=font, fill=255)
        x += font.getlength(ch) + track
    ink = canvas.crop(canvas.getbbox())
    w = round(width_in * PPI)
    h = round(ink.height * w / ink.width)
    small = ink.resize((w, h), Image.LANCZOS)
    # a few pixels clear all round, so the rims' shifts stay inside
    pad = 24
    out = Image.new("L", (w + pad * 2, h + pad * 2), 0)
    out.paste(small, (pad, pad))
    return np.asarray(out, np.float32) / 255.0, pad


def shifted(a, dx, dy):
    """a moved by (dx, dy) pixels, empty where it moved from"""
    out = np.zeros_like(a)
    h, w = a.shape
    out[max(dy, 0):h + min(dy, 0), max(dx, 0):w + min(dx, 0)] = a[max(-dy, 0):h + min(-dy, 0), max(-dx, 0):w + min(-dx, 0)]
    return out


def over(dst_rgb, dst_a, rgb, a):
    """paint (rgb, a) over (dst_rgb, dst_a), straight alpha"""
    out_a = a + dst_a * (1 - a)
    safe = np.where(out_a > 0, out_a, 1)
    out_rgb = (np.asarray(rgb, np.float32)[None, None, :] * a[..., None] + dst_rgb * (dst_a * (1 - a))[..., None]) / safe[..., None]
    return out_rgb, out_a


def finish(cov, kind, rim):
    # the walls of a pressed letter: lit from the upper left, the inner edge
    # facing the light (lower right) is lit, the one facing away is shaded
    shade = np.clip(cov - shifted(cov, rim, rim), 0, 1)  # inner upper-left edge
    light = np.clip(cov - shifted(cov, -rim, -rim), 0, 1)  # inner lower-right edge
    rgb = np.zeros(cov.shape + (3,), np.float32)
    a = np.zeros(cov.shape, np.float32)
    if kind == "imprint":
        rgb, a = over(rgb, a, (0, 0, 0), cov * 0.30)
        rgb, a = over(rgb, a, (0, 0, 0), shade * 0.50)
        rgb, a = over(rgb, a, (255, 255, 255), light * 0.30)
    else:
        g = np.asarray(GOLD[kind], np.float32)
        rgb, a = over(rgb, a, g, cov)
        rgb, a = over(rgb, a, g * 0.72, shade * 0.85)
        rgb, a = over(rgb, a, g + (255 - g) * 0.35, light * 0.85)
    img = Image.fromarray(np.dstack([np.clip(rgb, 0, 255), np.clip(a * 255, 0, 255)]).astype(np.uint8), "RGBA")
    box = img.getbbox()
    return img.crop(box)


lines = [
    "// GENERATED by scripts/make-cover-marks.py - the marks a printed cover draws,",
    "// as PNG pictures at 1200 ppi of their widest print size. Do not edit.",
    "",
    "export type CoverMarkShape = " + " | ".join(f'"{s}"' for s in SHAPES) + ";",
    'export type CoverMarkFinish = "imprint" | "gold" | "deep" | "dark";',
    "",
    "/** Each picture: its pixels, and its printed width at 1200 ppi (inches). */",
    "export const COVER_MARKS: Record<string, { png: string; width: number; height: number }> = {",
]
for shape, (text, face, width_in) in SHAPES.items():
    cov, pad = coverage(text, face, width_in)
    rim = max(4, round((0.010 if shape == "m-sans" else 0.006) * PPI))
    for kind in FINISHES[shape]:
        img = finish(cov, kind, rim)
        buf = io.BytesIO()
        img.save(buf, "PNG", optimize=True)
        data = base64.b64encode(buf.getvalue()).decode()
        lines.append(f'  "{shape}/{kind}": {{ png: "{data}", width: {img.width}, height: {img.height} }},')
        img.save(f"handoff/print-scans/mark-{shape}-{kind}.png")
        print(shape, kind, img.size, f"{len(buf.getvalue()) / 1024:.0f} KB")
lines.append("};")
lines.append("")
open(OUT, "w", encoding="utf-8").write("\n".join(lines))
print("wrote", OUT)
